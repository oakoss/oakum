#[test]
fn unretargetable_lockfile_leaves_manifests_untouched() {
    let root = temp_repo("bad-lock");
    cargo_package(&root, "demo");
    let before = fs::read_to_string(root.join("Cargo.toml")).unwrap();
    fs::write(
        root.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\nversion = 4\npackage = 4\n",
    )
    .expect("lock");
    write_patch_changeset(&root, "demo");

    let output = bin()
        .current_dir(&root)
        .arg("version")
        .output()
        .expect("run");
    assert!(
        !output.status.success(),
        "expected lock retarget to fail: {}",
        String::from_utf8_lossy(&output.stdout)
    );
    assert_eq!(fs::read_to_string(root.join("Cargo.toml")).unwrap(), before);
    assert_eq!(
        fs::read_to_string(root.join("Cargo.lock")).unwrap(),
        "# This file is automatically @generated by Cargo.\nversion = 4\npackage = 4\n"
    );
}

