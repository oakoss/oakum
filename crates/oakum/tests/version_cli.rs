#[test]
fn version_rewrites_workspace_table_and_member_version() {
    let root = temp_repo("inherit");
    fs::create_dir_all(root.join("crates/core/src")).unwrap();
    fs::create_dir_all(root.join("crates/app/src")).unwrap();
    fs::write(
        root.join("Cargo.toml"),
        "[workspace]\nresolver = \"2\"\nmembers = [\"crates/core\", \"crates/app\"]\n[workspace.dependencies]\ncore = { path = \"crates/core\", version = \"^0.1.0\" }\n",
    )
    .unwrap();
    fs::write(
        root.join("crates/core/Cargo.toml"),
        "[package]\nname = \"core\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    )
    .unwrap();
    fs::write(root.join("crates/core/src/lib.rs"), "").unwrap();
    fs::write(
        root.join("crates/app/Cargo.toml"),
        "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n[dependencies]\ncore = { workspace = true }\n",
    )
    .unwrap();
    fs::write(root.join("crates/app/src/lib.rs"), "").unwrap();
    fs::write(
        root.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"core\"\nversion = \"0.1.0\"\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\ndependencies = [\n \"core\",\n]\n",
    )
    .unwrap();
    write_patch_changeset(&root, "core");

    let output = bin()
        .current_dir(&root)
        .arg("version")
        .output()
        .expect("run");
    assert!(
        output.status.success(),
        "stderr: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let workspace = fs::read_to_string(root.join("Cargo.toml")).unwrap();
    assert!(
        workspace.contains("core = { path = \"crates/core\", version = \"^0.1.1\" }"),
        "{workspace}"
    );
    let core = fs::read_to_string(root.join("crates/core/Cargo.toml")).unwrap();
    assert!(core.contains("version = \"0.1.1\""), "{core}");
    let app = fs::read_to_string(root.join("crates/app/Cargo.toml")).unwrap();
    assert!(app.contains("core = { workspace = true }"), "{app}");
    assert!(app.contains("version = \"0.1.0\""), "{app}");
    let lock = fs::read_to_string(root.join("Cargo.lock")).unwrap();
    assert!(
        lock.contains("name = \"core\"\nversion = \"0.1.1\""),
        "{lock}"
    );
    assert_consumed(&root);
}

