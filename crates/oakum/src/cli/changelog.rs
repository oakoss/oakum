const CHANGELOG_NAME: &str = "CHANGELOG.md";
const TITLE: &str = "# Changelog";
const FOOTER_PREFIX: &str = "Generated by oakum ";

pub(super) struct ChangelogPlan<'a> {
    date: &'a str,
    tool_version: &'a str,
    template: Option<&'a str>,
    supplied_notes: Option<&'a str>,
    links: Option<&'a Links>,
}

impl<'a> ChangelogPlan<'a> {
    pub(super) fn new(
        date: &'a str,
        tool_version: &'a str,
        template: Option<&'a str>,
        supplied_notes: Option<&'a str>,
        links: Option<&'a Links>,
    ) -> Self {
        Self {
            date,
            tool_version,
            template,
            supplied_notes,
            links,
        }
    }
}

/// What a template can link to: the GitHub repository and, per bump file,
/// the commit that added it. Read only when the template reads `repo` or
/// `changes`, since each file costs one git child.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub(super) struct Links {
    pub(super) repo: Option<(String, String)>,
    pub(super) by_file: BTreeMap<String, Provenance>,
}

/// The commit that added a bump file. The pull request number is the
/// squash-merge convention `(#N)` at the end of the subject; a merge or a
/// direct push has none.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(super) struct Provenance {
    pub(super) commit: String,
    pub(super) author: String,
    pub(super) email: String,
    pub(super) subject: String,
}

impl Provenance {
    /// `None` when the file was never committed.
    ///
    /// # Errors
    ///
    /// The git read's own outcome class.
    pub(super) fn of(git: &Git, path: &str) -> Result<Option<Self>, CliError> {
        let Some(line) = git.optional_text(Op::FileAddedBy { path })? else {
            return Ok(None);
        };
        let mut fields = line.splitn(4, '\0');
        let (Some(commit), Some(author), Some(email), Some(subject)) =
            (fields.next(), fields.next(), fields.next(), fields.next())
        else {
            return Err(CliError::unverified(format!(
                "unverified: git log for `{path}` did not print four fields"
            )));
        };
        Ok(Some(Self {
            commit: commit.to_owned(),
            author: author.to_owned(),
            email: email.to_owned(),
            subject: subject.to_owned(),
        }))
    }

    pub(super) fn pull_request(&self) -> Option<u64> {
        pull_request_number(&self.subject)
    }
}

fn pull_request_number(subject: &str) -> Option<u64> {
    let trimmed = subject.trim_end();
    let inner = trimmed.strip_suffix(')')?;
    let (_, tail) = inner.rsplit_once("(#")?;
    tail.parse().ok()
}

/// # Errors
///
/// Clock before the Unix epoch.
pub(super) fn utc_date(now: SystemTime) -> Result<String, Box<dyn std::error::Error>> {
    let secs = now
        .duration_since(UNIX_EPOCH)
        .map_err(|_| CliError::new("system clock is before the Unix epoch"))?
        .as_secs();
    Ok(ymd_from_unix_days(secs / 86_400))
}

/// # Errors
///
/// Missing workspace package, template render failure, or a file oakum cannot splice.
pub(super) fn plan_changelog_writes(
    dir: &Dir,
    workspace: &Workspace,
    plan: &Plan,
    intent: &BTreeMap<PackageId, AggregatedBump>,
    input: &ChangelogPlan<'_>,
) -> Result<Vec<PlannedWrite>, Box<dyn std::error::Error>> {
    let mut sections_by_path: BTreeMap<PathBuf, Vec<String>> = BTreeMap::new();
    for change in plan.changes().values() {
        let package = workspace.get(change.id()).ok_or_else(|| {
            CliError::new(format!(
                "{} is in the plan but not in the workspace",
                change.id().name
            ))
        })?;
        let section = emit_section(package, change, intent.get(change.id()), plan, input)?;
        sections_by_path
            .entry(changelog_path(package))
            .or_default()
            .push(section);
    }

    let mut writes = Vec::new();
    for (path, sections) in sections_by_path {
        match read_text(dir, &path)? {
            None => {
                let next = assemble_new(&sections, input.tool_version);
                writes.push(PlannedWrite::create(path, next));
            }
            Some(original) => {
                let next = splice(&path, &original, &sections, input.tool_version)?;
                writes.push(PlannedWrite::new(path, original, next));
            }
        }
    }
    Ok(writes)
}

/// The changelog path as `release` hands it to git: repository-relative with
/// `/` separators, whatever the platform.
pub(super) fn changelog_repo_path(package: &Package) -> String {
    repo_path_display(&changelog_path(package))
}

fn changelog_path(package: &Package) -> PathBuf {
    let dir = package.manifest_dir();
    if dir.is_empty() {
        PathBuf::from(CHANGELOG_NAME)
    } else {
        Path::new(dir).join(CHANGELOG_NAME)
    }
}

fn emit_section(
    package: &Package,
    change: &PlannedChange,
    bump: Option<&AggregatedBump>,
    plan: &Plan,
    input: &ChangelogPlan<'_>,
) -> Result<String, Box<dyn std::error::Error>> {
    let notes = match input.supplied_notes {
        Some(body) => supplied_note(body).into_iter().collect(),
        None => release_notes(bump),
    };
    if let Some(source) = input.template {
        // A supplied body replaces the bump-file notes on every channel,
        // `changes` included.
        let bump = if input.supplied_notes.is_some() {
            None
        } else {
            bump
        };
        return render_template(source, package, change, bump, &notes, input);
    }
    if input.supplied_notes.is_some() {
        return Ok(supplied_section(
            change.to(),
            input.date,
            notes.first().copied(),
        ));
    }
    Ok(builtin_section(
        change.to(),
        input.date,
        bump,
        cascade_attribution(change, plan)?,
    ))
}

fn cascade_attribution<'a>(
    change: &'a PlannedChange,
    plan: &'a Plan,
) -> Result<Option<(&'a str, &'a Version)>, CliError> {
    match change.source() {
        ChangeSource::Intent => Ok(None),
        ChangeSource::Cascade { trigger } => {
            let Some(trigger_change) = plan.get(trigger) else {
                return Err(CliError::new(format!(
                    "{} cascaded from {trigger} but that package is not in the plan",
                    change.id()
                )));
            };
            Ok(Some((trigger.name.as_str(), trigger_change.to())))
        }
    }
}

fn supplied_section(version: &Version, date: &str, body: Option<&str>) -> String {
    match body {
        Some(body) => format!("## {version} ({date})\n\n{body}\n"),
        None => format!("## {version} ({date})\n"),
    }
}

/// Keep a Changelog's sections, in its order.
const SECTIONS: [&str; 6] = [
    "Added",
    "Changed",
    "Deprecated",
    "Removed",
    "Fixed",
    "Security",
];

fn builtin_section(
    version: &Version,
    date: &str,
    bump: Option<&AggregatedBump>,
    cascade: Option<(&str, &Version)>,
) -> String {
    let mut out = format!("## {version} ({date})\n");
    let mut grouped = grouped_notes(bump);
    let cascade_line = cascade.map(|(name, to)| format!("Updated {name} to {to}"));
    if let Some(line) = cascade_line.as_deref() {
        grouped[1].1.push(line);
    }
    for (heading, notes) in grouped {
        if notes.is_empty() {
            continue;
        }
        out.push('\n');
        out.push_str("### ");
        out.push_str(heading);
        out.push_str("\n\n");
        out.push_str(&notes.join("\n\n"));
        out.push('\n');
    }
    out
}

/// Notes by section, in Keep a Changelog order; every section is present so
/// the cascade line can join `Changed` by index.
fn grouped_notes(bump: Option<&AggregatedBump>) -> [(&'static str, Vec<&str>); 6] {
    let mut grouped = SECTIONS.map(|heading| (heading, Vec::new()));
    if let Some(bump) = bump {
        for contribution in bump.contributions() {
            if !contribution.level().is_release() {
                continue;
            }
            let Some((section, body)) = note_section(contribution.note(), contribution.level())
            else {
                continue;
            };
            if let Some(slot) = grouped.iter_mut().find(|(heading, _)| *heading == section) {
                slot.1.push(body);
            }
        }
    }
    grouped
}

/// A note that opens with one of Keep a Changelog's headings names its own
/// section and loses that line; the level is only the default, since `patch`
/// is not always a fix (`okm-6vf.15`). A heading-only note has no body and is
/// dropped like an empty one.
fn note_section(note: &str, level: BumpLevel) -> Option<(&'static str, &str)> {
    // Coverage-only notes never reach a changelog (ADR-0028), whatever
    // heading they open with.
    let default = match level {
        BumpLevel::Minor => "Added",
        BumpLevel::Major => "Changed",
        BumpLevel::Patch => "Fixed",
        BumpLevel::None => return None,
    };
    let body = note_body(note)?;
    let (first, rest) = body.split_once('\n').unwrap_or((body, ""));
    if let Some(named) = first.trim_end().strip_prefix("### ") {
        if let Some(section) = SECTIONS
            .iter()
            .find(|section| section.eq_ignore_ascii_case(named.trim()))
        {
            return note_body(rest).map(|rest| (*section, rest));
        }
    }
    Some((default, body))
}

fn release_notes(bump: Option<&AggregatedBump>) -> Vec<&str> {
    let Some(bump) = bump else {
        return Vec::new();
    };
    bump.contributions()
        .iter()
        .filter_map(|contribution| {
            note_section(contribution.note(), contribution.level()).map(|(_, body)| body)
        })
        .collect()
}

fn note_body(note: &str) -> Option<&str> {
    let note = note.trim_matches(['\n', '\r']);
    if note.is_empty() {
        None
    } else {
        Some(note)
    }
}

pub(super) fn supplied_note(body: &str) -> Option<&str> {
    let body = body.trim_end_matches(['\n', '\r']);
    if body.is_empty() {
        None
    } else {
        Some(body)
    }
}

#[derive(Serialize)]
struct SectionContext<'a> {
    version: String,
    date: &'a str,
    notes: Vec<&'a str>,
    changes: Vec<ChangeContext<'a>>,
    repo: Option<RepoContext>,
    package: &'a str,
    ecosystem: &'a str,
    bump: String,
    source: &'a str,
    trigger: Option<&'a str>,
    tool_version: &'a str,
    target: &'static str,
}

#[derive(Serialize)]
struct RepoContext {
    owner: String,
    name: String,
    url: String,
}

#[derive(Serialize)]
struct ChangeContext<'a> {
    note: &'a str,
    section: &'static str,
    level: String,
    file: &'a str,
    commit: Option<CommitContext>,
    pr: Option<PrContext>,
    author: Option<AuthorContext<'a>>,
}

#[derive(Serialize)]
struct CommitContext {
    sha: String,
    short: String,
    url: Option<String>,
}

#[derive(Serialize)]
struct PrContext {
    number: u64,
    url: Option<String>,
}

#[derive(Serialize)]
struct AuthorContext<'a> {
    name: &'a str,
    email: &'a str,
}

fn repo_context(links: Option<&Links>) -> Option<RepoContext> {
    let (owner, name) = links?.repo.clone()?;
    let url = format!("https://github.com/{owner}/{name}");
    Some(RepoContext { owner, name, url })
}

fn change_contexts<'a>(
    bump: Option<&'a AggregatedBump>,
    links: Option<&'a Links>,
) -> Vec<ChangeContext<'a>> {
    let Some(bump) = bump else {
        return Vec::new();
    };
    let repo_url = repo_context(links).map(|repo| repo.url);
    bump.contributions()
        .iter()
        .filter_map(|contribution| {
            let (section, note) = note_section(contribution.note(), contribution.level())?;
            let provenance = links.and_then(|links| links.by_file.get(contribution.source()));
            Some(ChangeContext {
                note,
                section,
                level: contribution.level().to_string(),
                file: contribution.source(),
                commit: provenance.map(|found| CommitContext {
                    sha: found.commit.clone(),
                    short: found.commit.chars().take(7).collect(),
                    url: repo_url
                        .as_ref()
                        .map(|url| format!("{url}/commit/{}", found.commit)),
                }),
                pr: provenance
                    .and_then(Provenance::pull_request)
                    .map(|number| PrContext {
                        number,
                        url: repo_url.as_ref().map(|url| format!("{url}/pull/{number}")),
                    }),
                author: provenance.map(|found| AuthorContext {
                    name: &found.author,
                    email: &found.email,
                }),
            })
        })
        .collect()
}

fn render_template(
    source: &str,
    package: &Package,
    change: &PlannedChange,
    bump: Option<&AggregatedBump>,
    notes: &[&str],
    input: &ChangelogPlan<'_>,
) -> Result<String, Box<dyn std::error::Error>> {
    let (source_kind, trigger) = match change.source() {
        ChangeSource::Intent => ("intent", None),
        ChangeSource::Cascade { trigger } => ("cascade", Some(trigger.name.as_str())),
    };
    let rendered = template::render(
        "changelog",
        source,
        SectionContext {
            version: change.to().to_string(),
            date: input.date,
            notes: notes.to_vec(),
            changes: change_contexts(bump, input.links),
            repo: repo_context(input.links),
            package: package.id().name.as_str(),
            ecosystem: ecosystem_label(package.id().ecosystem),
            bump: change.applied().effective().to_string(),
            source: source_kind,
            trigger,
            tool_version: input.tool_version,
            target: "changelog",
        },
    )
    .map_err(|err| CliError::new(err.to_string()))?;
    let mut rendered = rendered.trim_start_matches('\u{FEFF}').to_owned();
    if !rendered.ends_with('\n') {
        rendered.push('\n');
    }
    Ok(rendered)
}

fn ecosystem_label(ecosystem: Ecosystem) -> &'static str {
    match ecosystem {
        Ecosystem::Cargo => "cargo",
        Ecosystem::Npm => "npm",
    }
}

fn assemble_new(sections: &[String], tool_version: &str) -> String {
    let footer = format!("{FOOTER_PREFIX}{tool_version}.");
    join_blocks(&[TITLE, &sections.join("\n"), &footer])
}

fn splice(
    path: &Path,
    existing: &str,
    sections: &[String],
    tool_version: &str,
) -> Result<String, Box<dyn std::error::Error>> {
    if let Some(refusal) = splice_refusal(existing) {
        return Err(Box::new(CliError::new(refusal.reason(path))));
    }
    let body = strip_oakum_footer(existing);
    let new_sections = sections.join("\n");
    let footer = format!("{FOOTER_PREFIX}{tool_version}.");
    match version_heading_start(body) {
        Some(at) => {
            let prefix = &body[..at];
            let rest = &body[at..];
            Ok(join_blocks(&[prefix, &new_sections, rest, &footer]))
        }
        None => Ok(join_blocks(&[body, &new_sections, &footer])),
    }
}

/// The body under the `## <version>` heading, without the heading and the
/// oakum footer, trimmed of surrounding blank lines. `None` when no heading
/// names the version; `Some("")` for a heading with nothing under it. The
/// body ends at the next top- or second-level heading, since a migrated
/// changelog can carry non-version `##` sections. Lines inside a fenced code
/// block are never headings or footers: a note can quote a shell comment or
/// a changelog excerpt.
pub(super) fn version_section(text: &str, version: &Version) -> Option<String> {
    let mut fence = Fence::default();
    let mut lines = text.lines().map(|line| line.trim_end_matches('\r'));
    lines.find(|line| {
        !fence.observe(line)
            && line
                .strip_prefix("## ")
                .and_then(|rest| heading_version(rest, HeadingToken::Whole))
                .is_some_and(|found| found == *version)
    })?;
    let mut fence = Fence::default();
    let body: Vec<&str> = lines
        .take_while(|line| {
            fence.observe(line)
                || !(line.starts_with("## ") || line.starts_with("# ") || is_oakum_footer(line))
        })
        .collect();
    Some(body.join("\n").trim_matches('\n').to_owned())
}

/// Why `version` would refuse to splice into a changelog. `check` and
/// `migrate` ask the same question so a changesets title (`# @scope/pkg`)
/// is reported before the version job fails in CI.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum SpliceRefusal {
    Bom,
    Title,
}

impl SpliceRefusal {
    pub(super) fn reason(self, path: &Path) -> String {
        match self {
            Self::Bom => format!(
                "{} starts with a UTF-8 BOM; oakum will not splice a changelog it cannot recognize",
                repo_path_display(path)
            ),
            Self::Title => format!(
                "{} does not start with `{TITLE}`; oakum will not append without a recognized heading",
                repo_path_display(path)
            ),
        }
    }

    /// Editors keep a BOM when the first line is retyped, so the two fixes
    /// are not the same instruction.
    pub(super) fn fix(self) -> &'static str {
        match self {
            Self::Bom => "remove the byte-order mark from the start of the file",
            Self::Title => {
                "change the first line to `# Changelog` (the old title can stay as a line under it)"
            }
        }
    }
}

pub(super) fn splice_refusal(text: &str) -> Option<SpliceRefusal> {
    if text.starts_with('\u{FEFF}') {
        return Some(SpliceRefusal::Bom);
    }
    if !starts_with_title(text) {
        return Some(SpliceRefusal::Title);
    }
    None
}

/// The changelogs of `managed` packages that `version` would refuse, each as
/// `reason; fix`. Packages sharing a directory share one file and one report.
///
/// # Errors
///
/// A changelog that cannot be read.
pub(super) fn foreign_changelogs(
    dir: &Dir,
    workspace: &Workspace,
    managed: impl Fn(&Package) -> bool,
) -> Result<Vec<String>, Box<dyn std::error::Error>> {
    let mut seen = BTreeSet::new();
    let mut reports = Vec::new();
    for package in workspace.packages().filter(|package| managed(package)) {
        let path = changelog_path(package);
        if !seen.insert(path.clone()) {
            continue;
        }
        if let Some(text) = read_text(dir, &path)? {
            if let Some(refusal) = splice_refusal(&text) {
                reports.push(format!("{}; {}", refusal.reason(&path), refusal.fix()));
            }
        }
    }
    Ok(reports)
}

fn starts_with_title(text: &str) -> bool {
    let Some(rest) = text.strip_prefix(TITLE) else {
        return false;
    };
    rest.is_empty() || rest.starts_with('\n') || rest.starts_with("\r\n")
}

fn strip_oakum_footer(text: &str) -> &str {
    let trimmed = text.trim_end_matches(['\n', '\r']);
    let Some((rest, last)) = trimmed.rsplit_once('\n') else {
        return if is_oakum_footer(trimmed) {
            ""
        } else {
            trimmed
        };
    };
    let last = last.trim_end_matches('\r');
    if is_oakum_footer(last) {
        rest.trim_end_matches(['\n', '\r'])
    } else {
        trimmed
    }
}

fn is_oakum_footer(line: &str) -> bool {
    line.strip_prefix(FOOTER_PREFIX)
        .and_then(|rest| rest.strip_suffix('.'))
        .is_some_and(|version| Version::parse(version).is_ok())
}

fn version_heading_start(text: &str) -> Option<usize> {
    let mut pos = 0;
    let mut fence = Fence::default();
    for line in text.split_inclusive('\n') {
        let content = line.trim_end_matches(['\n', '\r']);
        if !fence.observe(content) && is_version_heading(content) {
            return Some(pos);
        }
        pos += line.len();
    }
    None
}

fn is_version_heading(line: &str) -> bool {
    let Some(rest) = line.strip_prefix("## ") else {
        return false;
    };
    heading_version(rest, HeadingToken::BeforeDate).is_some()
}

/// How a `## <version>` heading's token ends. Keep a Changelog writes
/// `## [1.2.3] - 2026-01-01`, so the splice point cuts at `-`; a lookup for
/// `0.1.1-rc.1` must match that heading and nothing else, so it keeps `-`.
#[derive(Clone, Copy)]
enum HeadingToken {
    Whole,
    BeforeDate,
}

fn heading_version(rest: &str, ends: HeadingToken) -> Option<Version> {
    let rest = rest.trim_start_matches('[').trim_start_matches('v');
    let cuts_dash = matches!(ends, HeadingToken::BeforeDate);
    let token = rest
        .split(|c: char| c == ']' || c == ' ' || c == '(' || (cuts_dash && c == '-'))
        .next()
        .unwrap_or("");
    Version::parse(token).ok()
}

fn join_blocks(blocks: &[&str]) -> String {
    let mut out = String::new();
    for block in blocks {
        let block = block.trim_end_matches(['\n', '\r']);
        if block.is_empty() {
            continue;
        }
        if !out.is_empty() {
            out.push_str("\n\n");
        }
        out.push_str(block);
    }
    out.push('\n');
    out
}

fn ymd_from_unix_days(days: u64) -> String {
    let (year, month, day) = civil_from_days(days);
    format!("{year:04}-{month:02}-{day:02}")
}

/// Civil date from days since 1970-01-01 (Howard Hinnant).
fn civil_from_days(days: u64) -> (i32, u8, u8) {
    let z = i64::try_from(days).unwrap_or(i64::MAX) + 719_468;
    let era = z / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let mut year = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    if month <= 2 {
        year += 1;
    }
    (
        i32::try_from(year).unwrap_or(i32::MAX),
        u8::try_from(month).unwrap_or(u8::MAX),
        u8::try_from(day).unwrap_or(u8::MAX),
    )
}

