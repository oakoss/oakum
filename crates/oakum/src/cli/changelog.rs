    fn bump(note: &str, level: BumpLevel) -> oakum::plan::AggregatedBump {
        let intent = aggregate([BumpFile {
            id: String::from("one.md"),
            entries: vec![(cargo("demo"), level)],
            note: String::from(note),
        }]);
        intent.into_values().next().expect("bump")
    }

